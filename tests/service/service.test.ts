test("service rejects overlaps while one model operation is active", async () => {
  const store = memory();
  let release: (() => void) | undefined;
  try {
    const service = createLabService({
      memory: store,
      now,
      controllerFor: () => async (input, signal) => {
        await new Promise<void>((resolve) => {
          release = resolve;
        });
        return createScenarioController(now)(input, signal);
      },
    });
    const pending = service.run(request("plan", "active"));
    await new Promise((resolve) => setTimeout(resolve, 0));
    rejects(await service.run(request("plan", "overlap")), "conflict");
    release!();
    unwrap(await pending);
  } finally {
    store.close();
  }
});

test("provider failure persists safe failed run without silently falling back to scenario", async () => {
  const store = memory();
  let calls = 0;
  try {
    const service = createLabService({
      memory: store,
      now,
      controllerFor: () => async () => {
        calls++;
        throw new ProviderControllerError(
          "unauthorized",
          "secret-key-and-prompt",
        );
      },
    });
    const value = unwrap(
      await service.run(request("plan", "failed", "openai")),
    );
    assert.equal(value.run.status, "failed");
    assert.equal(value.result.type, "failure");
    if (value.result.type === "failure")
      assert.equal(value.result.error.code, "unauthorized");
    assert.equal(
      JSON.stringify(value).includes("secret-key-and-prompt"),
      false,
    );
    assert.equal(
      value.memories.some((m) => m.recordedPayload.kind === "plan-proposal"),
      false,
    );
    unwrap(await service.run(request("plan", "failed", "openai")));
    assert.equal(calls, 1);
  } finally {
    store.close();
  }
});

