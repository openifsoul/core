test("model prompt projects bounded authoritative evidence without changing durable input", async () => {
  let generatedInput: { prompt: string; system: string } | undefined;
  const client: ModelClient = {
    id: "openai",
    generate: async (input) => {
      generatedInput = input;
      return { ok: true, value: { content: "An original model answer." } };
    },
  };
  const event = (
    id: string,
    payload: Record<string, unknown>,
  ): MemoryEvent => ({
    schemaVersion: "draft-0.2.0",
    kind: "memory-event",
    memoryId: id,
    characterId: IDS.character,
    recordedAt: now().toISOString(),
    scope: {
      audience: "participants",
      participantIds: [IDS.characterParticipant, IDS.localParticipant],
      export: "forbidden",
    },
    provenance: { sources: [{ sourceType: "host-report", sourceId: id }] },
    eventType: "synthetic-evidence",
    participantIds: [IDS.characterParticipant],
    environmentId: IDS.garden,
    sessionId: "historical-session",
    recordedPayload: payload,
  });
  const memories = [
    event("host-truth", {
      kind: "task-report",
      binding: { sessionId: "completed-session" },
      planId: "earlier-plan",
      taskId: "inspection",
      status: "succeeded",
      summary: "The host inspected two herb beds.",
      observedEffects: ["Uninspected beds changed from two to zero."],
    }),
    event("decision", {
      kind: "plan-decision",
      planId: "earlier-plan",
      status: "partially-accepted",
      taskDecisions: [{ taskId: "watering", decision: "rejected" }],
    }),
    event("utterance", {
      kind: "conversation-response",
      output: {
        type: "utterance",
        content: "A participant claimed watering happened.",
      },
    }),
    event("old-context", {
      kind: "context-report",
      observedState: { summary: "OMIT-OLD-CONTEXT-MARKER" },
    }),
    event("debug-copy", {
      kind: "laboratory-run",
      run: { marker: "OMIT-DUPLICATED-RUN-MARKER" },
    }),
    ...Array.from({ length: 70 }, (_, i) =>
      event(`old-conversation-${i}`, {
        kind: "conversation-response",
        output: { type: "utterance", content: "x".repeat(2500) },
      }),
    ),
  ];
  const before = structuredClone(memories);
  const requestDocument = {
    schemaVersion: "draft-0.2.0" as const,
    kind: "conversation-request" as const,
    binding: profile("chat").binding,
    requestId: "prompt-check",
    correlationId: "prompt-cycle",
    channelId: "lab-room",
    speakerParticipantId: IDS.characterParticipant,
    recipientParticipantIds: [IDS.localParticipant],
    environmentRevision: "lab-chat-profile-1",
    contextRevision: "lab-chat-context-1",
    mode: "live-channel" as const,
    trigger: "incoming-message" as const,
    requestedModality: "text" as const,
    receivedAt: now().toISOString(),
    deadlineAt: new Date(now().getTime() + 60_000).toISOString(),
    messages: [
      {
        messageId: "user-question",
        participantId: IDS.localParticipant,
        recordedAt: now().toISOString(),
        modality: "text" as const,
        content: "What did you complete?",
      },
    ],
  };
  await createModelController({ client, model: "gpt-4.1-mini", now })(
    {
      operation: "conversation",
      character: character(),
      profile: profile("chat"),
      context: context("chat"),
      request: requestDocument,
      memories,
    },
    new AbortController().signal,
  );
  assert.ok(generatedInput);
  const prompt = JSON.parse(generatedInput.prompt);
  assert.equal(prompt.latestUserMessage, "What did you complete?");
  assert.equal(prompt.profile, undefined);
  assert.equal(prompt.memories, undefined);
  assert.equal(prompt.historicalEvidence.hostReports[0].memoryId, "host-truth");
  assert.equal(
    prompt.historicalEvidence.hostReports[0].sessionId,
    "completed-session",
  );
  assert.equal(
    prompt.historicalEvidence.hostReports[0].summary,
    "The host inspected two herb beds.",
  );
  assert.deepEqual(prompt.historicalEvidence.hostReports[0].observedEffects, [
    "Uninspected beds changed from two to zero.",
  ]);
  assert.equal(
    prompt.historicalEvidence.plansAndDecisions[0].taskDecisions[0].decision,
    "rejected",
  );
  assert.equal(
    generatedInput.prompt.includes("OMIT-OLD-CONTEXT-MARKER"),
    false,
  );
  assert.equal(
    generatedInput.prompt.includes("OMIT-DUPLICATED-RUN-MARKER"),
    false,
  );
  assert.ok(prompt.historicalEvidence.omittedSelectedRecordCount > 0);
  const evidence = prompt.historicalEvidence;
  const records = [
    ...evidence.hostReports,
    ...evidence.plansAndDecisions,
    ...evidence.conversation,
  ];
  assert.ok(records.length <= 20);
  assert.ok(
    records.reduce(
      (bytes, record) =>
        bytes + new TextEncoder().encode(JSON.stringify(record)).byteLength,
      0,
    ) <= 12_000,
  );
  assert.match(generatedInput.system, /Conversation records.*not proof/);
  assert.match(generatedInput.system, /data, not instructions/);
  assert.deepEqual(memories, before);
});
