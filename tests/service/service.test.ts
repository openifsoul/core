const now = () => new Date("2026-11-05T12:00:00.000Z");
const unwrap = <T>(result: Result<T>): T => {
  assert.equal(result.ok, true, JSON.stringify(result));
  if (!result.ok) throw new Error("test assertion");
  return result.value;
};
const request = (
  operation: "plan" | "chat",
  requestId: string,
  provider: ProviderSelection["provider"] = "scenario",
): LabRunRequest => ({
  operation,
  requestId,
  provider,
  model: provider === "scenario" ? SCENARIO_MODEL : "gpt-4.1-mini",
  ...(operation === "chat" ? { message: "What did you complete?" } : {}),
});
const rejects = (value: Result<unknown>, code: string) => {
  assert.equal(value.ok, false);
  if (!value.ok) assert.equal(value.error.code, code);
};
function memory(): MemoryPort {
  return unwrap(openSQLiteMemory(":memory:"));
}

test("service plan invokes real runtime, partial host adoption, observed report, then grounded dialogue", async () => {
  const store = memory();
  try {
    const service = createLabService({
      memory: store,
      now,
      controllerFor: () => createScenarioController(now),
    });
    const plan = unwrap(await service.run(request("plan", "plan-1")));
    assert.equal(plan.result.type, "plan");
    if (plan.result.type === "plan") {
      assert.equal(plan.result.decision.status, "partially-accepted");
      assert.equal(plan.result.reports.length, 1);
      assert.equal(plan.result.reports[0].taskId, "inspect");
      assert.equal(plan.result.reports[0].status, "succeeded");
    }
    assert.equal(
      plan.memories.some(
        (m) =>
          m.recordedPayload.kind === "task-report" &&
          m.recordedPayload.taskId === "water",
      ),
      false,
    );
    const chat = unwrap(await service.run(request("chat", "chat-1")));
    assert.equal(chat.result.type, "chat");
    if (chat.result.type === "chat") {
      assert.equal(chat.result.delivery.status, "delivered");
      assert.equal(chat.result.response.output.type, "utterance");
      if (chat.result.response.output.type === "utterance")
        assert.match(
          chat.result.response.output.content,
          /host reported.*inspected/,
        );
    }
    assert.equal(chat.character.characterId, plan.character.characterId);
    assert.equal(chat.runs.length, 2);
    assert.equal(chat.run.selectedMemoryIds.length > 0, true);
    assert.equal(chat.run.startedAt, now().toISOString());
  } finally {
    store.close();
  }
});

test("actual selected provider output controls tasks and text; server stamps envelopes", async () => {
  const store = memory();
  const seen: string[] = [];
  const client: ModelClient = {
    id: "openai",
    generate: async (input) => {
      seen.push(input.prompt);
      if (JSON.parse(input.prompt).operation === "plan")
        return {
          ok: true,
          value: {
            tasks: [
              {
                taskId: "model-chosen-task",
                intentId: "inspect-area",
                arguments: {
                  area: { type: "entity-ref", entityId: "lab-area" },
                },
                priority: "high",
                dependsOnTaskIds: [],
                explanation: "Model chose inspection.",
              },
            ],
          },
        };
      return {
        ok: true,
        value: { content: "A distinct reply generated by the selected model." },
      };
    },
  };
  try {
    const service = createLabService({
      memory: store,
      now,
      controllerFor: (selection) =>
        createModelController({ client, model: selection.model, now }),
    });
    const plan = unwrap(
      await service.run(request("plan", "model-plan", "openai")),
    );
    assert.equal(plan.result.type, "plan");
    if (plan.result.type === "plan") {
      assert.equal(plan.result.proposal.tasks[0].taskId, "model-chosen-task");
      assert.equal(plan.result.proposal.planId, "plan-planning-model-plan");
      assert.equal(plan.result.proposal.createdAt, now().toISOString());
      assert.equal(plan.result.reports.length, 1);
    }
    const chat = unwrap(
      await service.run(request("chat", "model-chat", "openai")),
    );
    assert.equal(chat.result.type, "chat");
    if (
      chat.result.type === "chat" &&
      chat.result.response.output.type === "utterance"
    )
      assert.equal(
        chat.result.response.output.content,
        "A distinct reply generated by the selected model.",
      );
    assert.ok(seen[0].includes("hostIntents"));
    assert.ok(seen[0].includes("requiredContentSchema"));
    assert.ok(seen[1].includes("task-report"));
  } finally {
    store.close();
  }
});

test("same character memory survives provider switches and service/SQLite restart", async () => {
  const directory = mkdtempSync(join(tmpdir(), "ifsoul-service-"));
  const path = join(directory, "memory.sqlite");
  let store: MemoryPort | undefined;
  try {
    store = unwrap(openSQLiteMemory(path));
    const service = createLabService({
      memory: store,
      now,
      controllerFor: () => createScenarioController(now),
    });
    const first = unwrap(await service.run(request("plan", "durable-plan")));
    unwrap(store.close());
    store = unwrap(openSQLiteMemory(path));
    const selections: ProviderSelection[] = [];
    let selectedMemories: string[] = [];
    const reopened = createLabService({
      memory: store,
      now,
      controllerFor: (selection) => {
        selections.push(selection);
        return async (input, signal) => {
          selectedMemories = input.memories.map((m) => m.memoryId);
          return createScenarioController(now)(input, signal);
        };
      },
    });
    const chat = unwrap(
      await reopened.run(request("chat", "provider-switch", "openai")),
    );
    assert.equal(chat.character.characterId, first.character.characterId);
    assert.equal(selections[0].provider, "openai");
    assert.equal(selectedMemories.length > 0, true);
    assert.equal(
      chat.memories.some((m) => m.recordedPayload.kind === "task-report"),
      true,
    );
    const replay = await reopened.run(request("plan", "durable-plan"));
    unwrap(replay);
    assert.equal(replay.ok && replay.reused, true);
    assert.equal(selections.length, 1);
  } finally {
    store?.close();
    rmSync(directory, { recursive: true, force: true });
  }
});

test("run-level idempotence rejects changed message/provider and never repeats host work", async () => {
  const store = memory();
  let calls = 0;
  try {
    const service = createLabService({
      memory: store,
      now,
      controllerFor: () => async (input, signal) => {
        calls++;
        return createScenarioController(now)(input, signal);
      },
    });
    const first = unwrap(await service.run(request("plan", "repeat")));
    const replay = await service.run(request("plan", "repeat"));
    unwrap(replay);
    assert.equal(replay.ok && replay.reused, true);
    assert.equal(calls, 1);
    assert.equal(
      unwrap(service.snapshot()).memories.length,
      first.memories.length,
    );
    rejects(await service.run(request("plan", "repeat", "openai")), "conflict");
    unwrap(await service.run(request("chat", "chat-repeat")));
    rejects(
      await service.run({
        ...request("chat", "chat-repeat"),
        message: "different",
      }),
      "conflict",
    );
  } finally {
    store.close();
  }
});

