// Compile normative schemas ahead of time: Workers never execute Ajv code generation.
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { readFile, writeFile, mkdir } from "node:fs/promises";
const names = [
  "common",
  "character",
  "environment",
  "context",
  "planning",
  "conversation",
  "memory",
  "archive",
];
const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  code: { source: true },
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
});
addFormats(ajv);
for (const name of names)
  ajv.addSchema(
    JSON.parse(
      await readFile(
        new URL(
          `../packages/protocol/schemas/v0.2/${name}.schema.json`,
          import.meta.url,
        ),
        "utf8",
      ),
    ),
  );
const exports = Object.fromEntries(
  names
    .filter((n) => n !== "common")
    .map((n) => [n, `urn:ifsoul:protocol:draft-0.2.0:${n}`]),
);
const output =
  "// Generated by scripts/generate-validators.mjs. Do not edit.\n" +
  standalone(ajv, exports) +
  "\n";
const target = new URL(
  "../packages/protocol/src/generated/validators.cjs",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw Error(
      "Generated validators are stale. Run pnpm generate:validators.",
    );
} else {
  await mkdir(new URL("../packages/protocol/src/generated/", import.meta.url), {
    recursive: true,
  });
  await writeFile(target, output);
}
